#!/usr/bin/env python3
"""Writes x86_64_features.txt: for each target feature rustc knows on
x86-64 Linux, the LLVM features rustc turns on for it (its own and those it
implies, in LLVM's names: `rdrand` is `+rdrnd`), as rustc's own build of a
function says in its "target-features". Lowering gives a function with
`#[target_feature(enable = ...)]` those.

Run as a program: rustc, on PATH, for x86_64-unknown-linux-gnu.

    python3 gen_target_features.py > x86_64_features.txt
"""
import os
import re
import subprocess
import sys
import tempfile

TARGET = "x86_64-unknown-linux-gnu"


def main():
    listing = subprocess.run(
        ["rustc", "--print", "target-features", "--target", TARGET], capture_output=True, text=True, check=True
    ).stdout
    names = []
    for line in listing.splitlines():
        # (Rust's features only: not LLVM's, which #[target_feature] cannot name.)
        if line.startswith("Code-generation features"):
            break
        m = re.match(r"^    ([a-z0-9._-]+) +- ", line)
        if m and m.group(1) not in names:
            names.append(m.group(1))
    version = subprocess.run(["rustc", "--version"], capture_output=True, text=True).stdout.strip()
    print(f"# Generated by gen_target_features.py with {version}, for {TARGET}.")
    print("# Each Rust target feature, and the LLVM features rustc turns on for it.")
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, "e.rs")
        with open(src, "w") as f:
            f.write("pub fn f() {}\n")
        for name in names:
            out = os.path.join(d, "e.ll")
            r = subprocess.run(
                ["rustc", "--crate-type=lib", "--emit=llvm-ir", "-C", "opt-level=0", "--target", TARGET,
                 "-C", f"target-feature=+{name}", src, "-o", out],
                capture_output=True, text=True,
            )
            if r.returncode != 0 or not os.path.exists(out):
                continue
            m = re.search(r'"target-features"="([^"]*)"', open(out).read())
            if m:
                print(f"{name} {m.group(1)}")
            os.remove(out)


if __name__ == "__main__":
    sys.exit(main())
